// Runs the GPU specs (every *.webgl.test.ts and *.browser.test.ts beside this
// file) through a SafeLight checkout's WebGL test harness: headless Chromium
// on SwiftShader, the real renderer and the real stage injection, so the stage
// is checked where the node suite can't see: compilation with the host's
// namespacing, the bit-exact normal render, and the shader against the TS twin.
//
// The specs are copied into the checkout for the run (its harness helpers and
// path aliases only resolve from inside) and removed again afterwards, along
// with the generated config. SAFELIGHT_CORE points at the checkout (default:
// a SafeLight directory beside this repository or beside its parent folder).
// The browser server takes a port the OS hands out, since Windows' dynamic
// port exclusions can swallow vitest's fixed default. SAFELIGHT_TEST_CHROME
// overrides the browser executable when Playwright's bundled Chromium won't
// start. Launch options go through playwright({ launchOptions }), which
// vitest 4.1 reads, and through the instance's `launch` as well.
//
// The extension folder is served at /__plugins__/hdr-editing/, as the app
// serves an installed extension, so the AVIF worker spec runs the built
// dist/avif-worker.js. A dist/ older than src/ is refused: the spec would test
// a stale worker.
"use strict";

const fs = require("fs");
const net = require("net");
const path = require("path");
const { spawnSync } = require("child_process");

const extension = path.resolve(__dirname, "..", "..");
const isCheckout = (dir) => fs.existsSync(path.join(dir, "vitest.webgl.config.ts"));
const candidates = process.env.SAFELIGHT_CORE
  ? [path.resolve(process.env.SAFELIGHT_CORE)]
  : [path.join(extension, "..", "SafeLight"), path.join(extension, "..", "..", "SafeLight")];
const core = candidates.find(isCheckout);
if (!core) {
  console.error(`No SafeLight checkout found (tried ${candidates.join(", ")}); set SAFELIGHT_CORE`);
  process.exit(2);
}

const builtWorker = path.join(extension, "dist", "avif-worker.js");
const newestSource = fs
  .readdirSync(path.join(extension, "src"))
  .reduce((t, f) => Math.max(t, fs.statSync(path.join(extension, "src", f)).mtimeMs), 0);
if (!fs.existsSync(builtWorker) || fs.statSync(builtWorker).mtimeMs < newestSource) {
  console.error(`${builtWorker} is missing or older than src/; run npm run build first`);
  process.exit(2);
}

const specDir = path.join(core, "src", "rendering", "webgl", "__hdr_gpu__");
const configFile = path.join(core, "vitest.hdr-gpu.config.ts");
const executablePath = process.env.SAFELIGHT_TEST_CHROME;

const config = (port) => `/// <reference types="vitest/config" />
// Generated by the HDR Editing extension's test/gpu/run.cjs and removed
// after the run. Same rig as vitest.webgl.config.ts, plus the extension's
// sources and its copied spec.
import path from "path";
import { createReadStream, readFileSync, statSync } from "fs";
import { defineConfig } from "vite";
import { playwright } from "@vitest/browser-playwright";

const pkg = JSON.parse(readFileSync(path.resolve(__dirname, "package.json"), "utf-8")) as { version: string };
const EXT = ${JSON.stringify(extension)};

const TYPES: Record<string, string> = { ".js": "text/javascript", ".wasm": "application/wasm", ".json": "application/json" };

export default defineConfig({
  cacheDir: "node_modules/.vite-cache-hdr-gpu",
  plugins: [
    {
      name: "hdr-plugin-folder",
      configureServer(server) {
        server.middlewares.use("/__plugins__/hdr-editing/", (req, res, next) => {
          const rel = decodeURIComponent((req.url ?? "").split("?")[0]).replace(/^[/]+/, "");
          const file = path.resolve(EXT, rel);
          let isFile = false;
          try {
            isFile = file.startsWith(EXT + path.sep) && statSync(file).isFile();
          } catch {
            isFile = false;
          }
          if (!isFile) {
            res.statusCode = 404;
            res.end();
            return;
          }
          res.setHeader("Content-Type", TYPES[path.extname(file)] ?? "application/octet-stream");
          createReadStream(file).pipe(res);
        });
      },
    },
  ],
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  resolve: {
    alias: {
      "@": path.resolve(__dirname, "src"),
      "libraw-wasm": path.resolve(__dirname, "src/raw/vendor/libraw-wasm/index.js"),
      "@hdr": path.join(EXT, "src"),
      "@hdr-test": path.join(EXT, "test"),
      "@hdr-modules": path.join(EXT, "node_modules"),
    },
  },
  server: { fs: { allow: [__dirname, EXT] } },
  optimizeDeps: { exclude: ["libraw-wasm"] },
  test: {
    name: "hdr-gpu",
    include: ["src/rendering/webgl/__hdr_gpu__/*.test.ts"],
    testTimeout: 600_000,
    browser: {
      enabled: true,
      headless: true,
      provider: playwright({
        launchOptions: {
          ${executablePath ? `executablePath: ${JSON.stringify(executablePath)},` : ""}
          args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"],
        },
      }),
      api: { port: ${port}, strictPort: true },
      // Also per instance: the local rig on this machine has passed system
      // Chrome this way, and setting both costs nothing.
      instances: [
        {
          browser: "chromium",
          launch: {
            ${executablePath ? `executablePath: ${JSON.stringify(executablePath)},` : ""}
            args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"],
          },
        },
      ],
    },
  },
});
`;

function freePort() {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.unref();
    server.on("error", reject);
    server.listen(0, "127.0.0.1", () => {
      const { port } = server.address();
      server.close(() => resolve(port));
    });
  });
}

async function main() {
  const port = await freePort();
  let status = 1;
  try {
    fs.mkdirSync(specDir, { recursive: true });
    for (const file of fs.readdirSync(__dirname)) {
      if (/\.(webgl|browser)\.test\.ts$/.test(file)) fs.copyFileSync(path.join(__dirname, file), path.join(specDir, file));
    }
    fs.writeFileSync(configFile, config(port));
    const result = spawnSync("npx", ["vitest", "run", "--config", path.basename(configFile), "--reporter=verbose"], {
      cwd: core,
      stdio: "inherit",
      shell: true,
    });
    status = result.status ?? 1;
  } finally {
    fs.rmSync(specDir, { recursive: true, force: true });
    fs.rmSync(configFile, { force: true });
  }
  process.exit(status);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
